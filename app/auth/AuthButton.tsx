'use client';

import { signIn, signOut, useSession } from 'next-auth/react';

export function AuthButton() {
  const { data: session, status } = useSession();

  if (status === 'loading') {
    return (
      <span className="skeleton" style={{ height: 32, width: 100, borderRadius: 99 }} />
    );
  }

  return session ? (
    <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
      <span className="auth-user-name">Hello, {session.user?.name}</span>
      <form
        action={async () => {
          await signOut();
        }}
      >
        <button type="submit" className="btn btn--secondary btn--sm">
          <span className="btn__label">Sign out</span>
          <span className="btn__label btn__label--dup" aria-hidden="true">Sign out</span>
        </button>
      </form>
    </div>
  ) : (
    <button
      type="button"
      onClick={() => signIn('discord', { callbackUrl: '/' })}
      className="signin__btn signin__btn--discord"
      style={{ width: 'auto', height: 32, padding: '0 14px', fontSize: 13 }}
    >
      <DiscordIcon />
      <span>Sign in</span>
    </button>
  );
}

